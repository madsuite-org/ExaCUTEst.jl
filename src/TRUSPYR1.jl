function truspyr1_model(; T = Float64, backend = nothing, kwargs...)
    # TRUSPYR1: 8-bar pyramid truss, minimize weight
    # 11 vars: XAREA(1..8)≥1 [x[1..8]], DISPL(1..3) free [x[9..11]]
    # 4 constraints: EQUIL(1..3) [E], STREN [L≤0]
    # Computed: GAMMA(J)=E/L(J)^3, RR(I,J,K)=GAMMA(J)*R(I,J)*R(K,J)

    sqrt105 = sqrt(105.0)
    ALPHA = T(0.3291726437)
    Q1 = T(2.0/sqrt105); Q2 = T(1.0/sqrt105); Q3 = T(10.0/sqrt105)

    # Precomputed bar weights: L(1..4)=sqrt(17)/8, L(5..8)=sqrt(18)/8
    sqrt17 = sqrt(17.0); sqrt18 = sqrt(18.0)
    L14 = sqrt17/8.0; L58 = sqrt18/8.0
    W14 = T(0.78 * L14); W58 = T(0.78 * L58)

    c = ExaModels.ExaCore(T; backend = backend, concrete = Val(true))
    ExaModels.@add_var(c, x, 11;
        lvar = T[fill(1.0, 8); fill(-Inf, 3)],
        uvar = T(Inf),
        start = T(0))

    # Objective: sum_J W(J)*XAREA(J)
    ExaModels.@add_obj(c, W14 * x[1] + W14 * x[2] + W14 * x[3] + W14 * x[4]
                        + W58 * x[5] + W58 * x[6] + W58 * x[7] + W58 * x[8])

    # EQUIL(1): precomputed RR terms - P1=40
    ExaModels.@add_con(c,
        T(9.587290589671516)  * x[9]  * x[1]
      + T(9.587290589671516)  * x[9]  * x[2]
      + T(9.587290589671516)  * x[9]  * x[3]
      + T(9.587290589671516)  * x[9]  * x[4]
      + T(19.798989873223338) * x[9]  * x[5]
      + T(19.798989873223338) * x[9]  * x[7]
      + T(9.587290589671516)  * x[10] * x[1]
      + T(-9.587290589671516) * x[10] * x[2]
      + T(9.587290589671516)  * x[10] * x[3]
      + T(-9.587290589671516) * x[10] * x[4]
      + T(14.380935884507274) * x[11] * x[1]
      + T(14.380935884507274) * x[11] * x[2]
      + T(-14.380935884507274)* x[11] * x[3]
      + T(-14.380935884507274)* x[11] * x[4]
      + T(19.798989873223338) * x[11] * x[5]
      + T(-19.798989873223338)* x[11] * x[7]
      - T(40.0))

    # EQUIL(2): P2=20
    ExaModels.@add_con(c,
        T(9.587290589671516)  * x[9]  * x[1]
      + T(-9.587290589671516) * x[9]  * x[2]
      + T(9.587290589671516)  * x[9]  * x[3]
      + T(-9.587290589671516) * x[9]  * x[4]
      + T(9.587290589671516)  * x[10] * x[1]
      + T(9.587290589671516)  * x[10] * x[2]
      + T(9.587290589671516)  * x[10] * x[3]
      + T(9.587290589671516)  * x[10] * x[4]
      + T(19.798989873223338) * x[10] * x[6]
      + T(19.798989873223338) * x[10] * x[8]
      + T(14.380935884507274) * x[11] * x[1]
      + T(-14.380935884507274)* x[11] * x[2]
      + T(-14.380935884507274)* x[11] * x[3]
      + T(14.380935884507274) * x[11] * x[4]
      + T(-19.798989873223338)* x[11] * x[6]
      + T(19.798989873223338) * x[11] * x[8]
      - T(20.0))

    # EQUIL(3): P3=200
    ExaModels.@add_con(c,
        T(14.380935884507274) * x[9]  * x[1]
      + T(14.380935884507274) * x[9]  * x[2]
      + T(-14.380935884507274)* x[9]  * x[3]
      + T(-14.380935884507274)* x[9]  * x[4]
      + T(19.798989873223338) * x[9]  * x[5]
      + T(-19.798989873223338)* x[9]  * x[7]
      + T(14.380935884507274) * x[10] * x[1]
      + T(-14.380935884507274)* x[10] * x[2]
      + T(-14.380935884507274)* x[10] * x[3]
      + T(14.380935884507274) * x[10] * x[4]
      + T(-19.798989873223338)* x[10] * x[6]
      + T(19.798989873223338) * x[10] * x[8]
      + T(21.57140382676091)  * x[11] * x[1]
      + T(21.57140382676091)  * x[11] * x[2]
      + T(21.57140382676091)  * x[11] * x[3]
      + T(21.57140382676091)  * x[11] * x[4]
      + T(19.798989873223338) * x[11] * x[5]
      + T(19.798989873223338) * x[11] * x[6]
      + T(19.798989873223338) * x[11] * x[7]
      + T(19.798989873223338) * x[11] * x[8]
      - T(200.0))

    # STREN (L≤0): Q1*D1 + Q2*D2 + Q3*D3 - ALPHA ≤ 0
    ExaModels.@add_con(c, Q1*x[9] + Q2*x[10] + Q3*x[11] - ALPHA; lcon = T(-Inf), ucon = T(0))

    return ExaModels.ExaModel(c; kwargs...)
end

function truspyr2_model(; T = Float64, backend = nothing, kwargs...)
    # TRUSPYR2: pyramid truss, 11 vars, 11 constraints (3 equilibrium + 8 stress)
    # STRES(J) (L≤0): R(1,J)*D1 + R(2,J)*D2 + R(3,J)*D3 - STRUP(J) ≤ 0

    sqrt17 = sqrt(17.0); sqrt18 = sqrt(18.0)
    L14 = sqrt17/8.0; L58 = sqrt18/8.0
    W14 = T(0.78 * L14); W58 = T(0.78 * L58)
    E_mod = 21.0

    STRUP = T[L14^2/E_mod*10, L14^2/E_mod*10, L14^2/E_mod*10, L14^2/E_mod*10,
              L58^2/E_mod*10, L58^2/E_mod*10, L58^2/E_mod*10, L58^2/E_mod*10]

    # R(I,J): direction cosines
    R = T[0.250  0.250  -0.250 -0.250  0.375  0.000 -0.375  0.000;
          0.250 -0.250  -0.250  0.250  0.000 -0.375  0.000  0.375;
          0.375  0.375   0.375  0.375  0.375  0.375  0.375  0.375]

    c = ExaModels.ExaCore(T; backend = backend, concrete = Val(true))
    ExaModels.@add_var(c, x, 11;
        lvar = T[fill(1.0, 8); fill(-Inf, 3)],
        uvar = T(Inf),
        start = T(0))

    ExaModels.@add_obj(c, W14 * x[1] + W14 * x[2] + W14 * x[3] + W14 * x[4]
                        + W58 * x[5] + W58 * x[6] + W58 * x[7] + W58 * x[8])

    # EQUIL(1)
    ExaModels.@add_con(c,
        T(9.587290589671516)  * x[9]  * x[1]
      + T(9.587290589671516)  * x[9]  * x[2]
      + T(9.587290589671516)  * x[9]  * x[3]
      + T(9.587290589671516)  * x[9]  * x[4]
      + T(19.798989873223338) * x[9]  * x[5]
      + T(19.798989873223338) * x[9]  * x[7]
      + T(9.587290589671516)  * x[10] * x[1]
      + T(-9.587290589671516) * x[10] * x[2]
      + T(9.587290589671516)  * x[10] * x[3]
      + T(-9.587290589671516) * x[10] * x[4]
      + T(14.380935884507274) * x[11] * x[1]
      + T(14.380935884507274) * x[11] * x[2]
      + T(-14.380935884507274)* x[11] * x[3]
      + T(-14.380935884507274)* x[11] * x[4]
      + T(19.798989873223338) * x[11] * x[5]
      + T(-19.798989873223338)* x[11] * x[7]
      - T(40.0))
    # EQUIL(2)
    ExaModels.@add_con(c,
        T(9.587290589671516)  * x[9]  * x[1]
      + T(-9.587290589671516) * x[9]  * x[2]
      + T(9.587290589671516)  * x[9]  * x[3]
      + T(-9.587290589671516) * x[9]  * x[4]
      + T(9.587290589671516)  * x[10] * x[1]
      + T(9.587290589671516)  * x[10] * x[2]
      + T(9.587290589671516)  * x[10] * x[3]
      + T(9.587290589671516)  * x[10] * x[4]
      + T(19.798989873223338) * x[10] * x[6]
      + T(19.798989873223338) * x[10] * x[8]
      + T(14.380935884507274) * x[11] * x[1]
      + T(-14.380935884507274)* x[11] * x[2]
      + T(-14.380935884507274)* x[11] * x[3]
      + T(14.380935884507274) * x[11] * x[4]
      + T(-19.798989873223338)* x[11] * x[6]
      + T(19.798989873223338) * x[11] * x[8]
      - T(20.0))
    # EQUIL(3)
    ExaModels.@add_con(c,
        T(14.380935884507274) * x[9]  * x[1]
      + T(14.380935884507274) * x[9]  * x[2]
      + T(-14.380935884507274)* x[9]  * x[3]
      + T(-14.380935884507274)* x[9]  * x[4]
      + T(19.798989873223338) * x[9]  * x[5]
      + T(-19.798989873223338)* x[9]  * x[7]
      + T(14.380935884507274) * x[10] * x[1]
      + T(-14.380935884507274)* x[10] * x[2]
      + T(-14.380935884507274)* x[10] * x[3]
      + T(14.380935884507274) * x[10] * x[4]
      + T(-19.798989873223338)* x[10] * x[6]
      + T(19.798989873223338) * x[10] * x[8]
      + T(21.57140382676091)  * x[11] * x[1]
      + T(21.57140382676091)  * x[11] * x[2]
      + T(21.57140382676091)  * x[11] * x[3]
      + T(21.57140382676091)  * x[11] * x[4]
      + T(19.798989873223338) * x[11] * x[5]
      + T(19.798989873223338) * x[11] * x[6]
      + T(19.798989873223338) * x[11] * x[7]
      + T(19.798989873223338) * x[11] * x[8]
      - T(200.0))

    # STRES(J) (L≤0): R[1,j]*D1 + R[2,j]*D2 + R[3,j]*D3 - STRUP(J) ≤ 0 for J=1..8
    ExaModels.@add_par(c, strup_par, STRUP)
    ExaModels.@add_par(c, R1p, T[R[1,j] for j in 1:8])
    ExaModels.@add_par(c, R2p, T[R[2,j] for j in 1:8])
    ExaModels.@add_par(c, R3p, T[R[3,j] for j in 1:8])
    ExaModels.@add_con(c,
        R1p[j]*x[9] + R2p[j]*x[10] + R3p[j]*x[11] - strup_par[j]
        for j in 1:8; lcon = T(-Inf), ucon = T(0))

    return ExaModels.ExaModel(c; kwargs...)
end
