    h1p3nu = (1.0 + 3.0 * nu) / 2.0   # 0.95
    h1pnu  = (1.0 + nu) / 2.0         # 0.65
    h3pnu  = (3.0 + nu) / 2.0         # 1.65

    # Radius at each grid point k = 0..K
    rk_arr = [ri + k * dr for k in 0:K]   # length K+1

    # SR(k) linear coefficients (k=0..K-1)
    sr_c1 = T[aux3g * rk_arr[k+1]^2 for k in 0:K-1]     # coef for w(k)
    sr_c2 = T[aux3g * rk_arr[k+2]^2 for k in 0:K-1]     # coef for w(k+1)
    sr_rk = T[rk_arr[k+1] for k in 0:K-1]               # rk for element coef
    sr_r1 = T[rk_arr[k+2] for k in 0:K-1]               # rk+1 for element coef

    # ST(k) coefficients (purely linear, k=0..K-1)
    st_c3 = T[(h1p3nu * rk_arr[k+1] - h1pnu * rk_arr[k+2]) / rk_arr[k+1] for k in 0:K-1]
    st_c4 = T[(h1pnu * rk_arr[k+2] - h3pnu * rk_arr[k+1]) / rk_arr[k+1] for k in 0:K-1]
    st_c5 = T[(h1pnu * rk_arr[k+1] - h1p3nu * rk_arr[k+2]) / rk_arr[k+2] for k in 0:K-1]
    st_c6 = T[(h3pnu * rk_arr[k+2] - h1pnu * rk_arr[k+1]) / rk_arr[k+2] for k in 0:K-1]
    # ST RHS from temperature law: E*epsc*(t_k - t_{k+1}), n=4
    st_rhs = T[Eepsc * ((tempo + tempn * (rk_arr[k+1] / ro)^4) - (tempo + tempn * (rk_arr[k+2] / ro)^4)) for k in 0:K-1]

