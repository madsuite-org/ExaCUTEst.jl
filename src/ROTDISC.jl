    c = ExaModels.ExaCore(T; backend = backend, concrete = Val(true))
    ExaModels.@add_var(c, x, nvar; lvar = lvar, uvar = uvar, start = start_vals)

    # Objective WEIGHT: linear sum over w(k)
    ExaModels.@add_par(c, wcoef, T[weight_c[k+1] for k in 0:K])
    ExaModels.@add_obj(c, wcoef[k+1] * x[idxw(k)] for k in 0:K)

    # SR(k) constraints (k=0..K-1), SCALE=100:
    # [sr_c1[k]*w(k) + sr_c2[k]*w(k+1) - rk*w(k)*sigr(k) + rk1*w(k+1)*sigr(k+1)
    #  - dr/2*w(k)*sigt(k) - dr/2*w(k+1)*sigt(k+1)] / 100 = 0
    ExaModels.@add_par(c, sr_c1p, sr_c1)
    ExaModels.@add_par(c, sr_c2p, sr_c2)
    ExaModels.@add_par(c, sr_rkp, sr_rk)
    ExaModels.@add_par(c, sr_r1p, sr_r1)
    hdr = T(dr / 2)   # dr/2 = 0.25
    ExaModels.@add_con(c,
        (sr_c1p[k+1] * x[idxw(k)] + sr_c2p[k+1] * x[idxw(k+1)]
         - sr_rkp[k+1] * x[idxw(k)] * x[idxsigr(k)]
         + sr_r1p[k+1] * x[idxw(k+1)] * x[idxsigr(k+1)]
         - hdr * x[idxw(k)] * x[idxsigt(k)]
         - hdr * x[idxw(k+1)] * x[idxsigt(k+1)]) / T(ech1)
        for k in 0:K-1)

    # ST(k) constraints (k=0..K-1), linear, no scale:
    # c3*sigr(k) + c4*sigt(k) + c5*sigr(k+1) + c6*sigt(k+1) - rhs = 0
    ExaModels.@add_par(c, st_c3p, st_c3)
    ExaModels.@add_par(c, st_c4p, st_c4)
    ExaModels.@add_par(c, st_c5p, st_c5)
    ExaModels.@add_par(c, st_c6p, st_c6)
    ExaModels.@add_par(c, st_rhsp, st_rhs)
    ExaModels.@add_con(c,
        st_c3p[k+1] * x[idxsigr(k)] + st_c4p[k+1] * x[idxsigt(k)]
        + st_c5p[k+1] * x[idxsigr(k+1)] + st_c6p[k+1] * x[idxsigt(k+1)]
        - st_rhsp[k+1]
        for k in 0:K-1)

    # STAy(k) constraints (k=0..K-1):
    # y(k+1) - y(k) - dr/2 * w(k)*sigt(k) - dr/2 * w(k+1)*sigt(k+1) = 0
    ExaModels.@add_con(c,
        x[idxy(k+1)] - x[idxy(k)]
        - hdr * x[idxw(k)] * x[idxsigt(k)]
        - hdr * x[idxw(k+1)] * x[idxsigt(k+1)]
        for k in 0:K-1)

    # STAx(k) constraints (k=0..K-1), purely linear:
    # x(k+1) - x(k) - dr/2 * w(k+1) - dr/2 * w(k) = 0
    ExaModels.@add_con(c,
        x[idxx(k+1)] - x[idxx(k)] - hdr * x[idxw(k+1)] - hdr * x[idxw(k)]
        for k in 0:K-1)

    # SLOP(k): w(k+1) - w(k) - 4*dr ≤ 0 (lcon=-Inf, ucon=0)
    slop_rhs = T(4 * dr)  # 2.0
    ExaModels.@add_con(c,
        x[idxw(k+1)] - x[idxw(k)] - slop_rhs
        for k in 0:K-1;
        lcon = T(-Inf), ucon = T(0))

    # SLOM(k): w(k) - w(k+1) - 4*dr ≤ 0 (lcon=-Inf, ucon=0)
    ExaModels.@add_con(c,
        x[idxw(k)] - x[idxw(k+1)] - slop_rhs
        for k in 0:K-1;
        lcon = T(-Inf), ucon = T(0))

    # AVsigt: y(K) - sigmatA * x(K) ≤ 0
    ExaModels.@add_con(c,
        x[idxy(K)] - T(sigmatA) * x[idxx(K)];
        lcon = T(-Inf), ucon = T(0))

    return ExaModels.ExaModel(c; kwargs...)
