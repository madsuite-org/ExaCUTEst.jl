# ROTDISC: Optimal design of a rotating disk of minimal weight
# Source: B. Apraxine and E. Loute, Facultes Universitaires Saint Louis, Brussels, 1993.
# SIF input: E. Loute and Ph. L. Toint, April 1993; correction by Ph. Shott, Jan 1995.
# classification LQR2-RN-905-1081
#
# K=180 intervals, 5*(K+1)=905 variables (w,sigt,sigr,x,y for k=0..K)
# Variable ordering: for each k=0..180: w(k), sigt(k), sigr(k), x(k), y(k)
#   Indices: w(k)=5k+1, sigt(k)=5k+2, sigr(k)=5k+3, x(k)=5k+4, y(k)=5k+5
#
# Element type 2PR: F(X,Y) = X*Y
# Objective WEIGHT: linear in w(k)
# Constraints (1081 total):
#   SR(0..K-1): equality (E, SCALE=100), nonlinear: w*sigr and w*sigt products
#   ST(0..K-1): equality (E), linear in sigr and sigt
#   STAy(0..K-1): equality (E), nonlinear: w*sigt products
#   STAx(0..K-1): equality (E), linear
#   SLOP(0..K-1): inequality (L≤0): w(k+1)-w(k) ≤ 4*dr
#   SLOM(0..K-1): inequality (L≤0): w(k)-w(k+1) ≤ 4*dr
#   AVsigt: inequality (L≤0): y(K) - sigmatA*x(K) ≤ 0
