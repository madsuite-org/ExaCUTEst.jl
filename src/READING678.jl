# READING6, READING7, READING8: Nonlinear optimal control (tide modelling)
# Source: Lyle & Nichols (1991) / Gould, Feb 1995 — variants with different N and G/Q data
# Variables: P(0..N) (state), A(0..N) (control), total 2N+2
# Julia: x[i+1] = P(i), x[N+2+i] = A(i)  for i=0..N
#
# Objective: sum_{J=1}^{N-1} (-A(J)*P(J)^2)  +  (-0.5)*A(N)*P(N)^2
#   (AP2 element: F=-A*P^2; coeff 1 for J=1..N-1, 0.5 for J=N)
#
# Constraints C(c_i) for c_i=1..N  [c_i = I+1, SIF I=0..N-1]  (E type = 0):
#   L1*P(c_i) + L2*P(c_i-1)  +  sum_{j=2}^{c_i-1} L3(c_i,j)*P(j-1)
#   +  CKD2*A(c_i)*P(c_i)  +  CKD2*A(c_i-1)*P(c_i-1)  =  RHS(c_i)
# where in Julia indices: P(k) = x[k+1], A(k) = x[N+k+2]
# and L3(c_i, j) = -(g[c_i-j+1] + g[c_i-j+2]) * two_CD24
# and RHS(c_i) = (q[c_i] + q[c_i+1]) * D2
#
# Parameters: C=2410, K=9.5e-4, D2=(10/N)/2
# L1 = 1 - g[1]*CD24   where CD24 = C*(D2^2)
# L2 = -1 - (g[1]+2*g[2])*CD24
# CKD2 = C*K*D2
# Bounds: P(0) fixed=0; P(1..N) free; A(0..N) in [0,1]; start=0

function reading6_model(; T = Float64, backend = nothing, kwargs...)
    N        = 50
    C        = T(2.41e3)
    K        = T(0.95e-3)
    D2       = T(10) / T(N) / T(2)   # DELTAT/2 = (10/N)/2
    CD24     = C * D2^2               # C*(D/2)^2
    two_CD24 = T(2) * CD24
    CKD2     = C * K * D2

    # g[k+1]=G(k), q[k+1]=Q(k) for k=0..N  (data from SIF)
    g = T.(Float64[
        -0.0020627, -0.00099414, -0.00057942, -0.00036153, -0.0002198, -0.00011452, -4.4283e-05, 4.0651e-05,
        0.00010438, 0.00011511, 0.00014736, 0.00016264, 0.00019018, 0.00019992, 0.00021341, 0.00023507,
        0.00024552, 0.00025497, 0.00026397, 0.00027167, 0.00026796, 0.0002698, 0.00026349, 0.00025023,
        0.0002304, 0.00020245, 0.00017031, 0.00012704, 7.9276e-05, 2.8594e-05, -2.3288e-05, -7.2e-05,
        -0.00011627, -0.00015002, -0.00017517, -0.00018623, -0.00018593, -0.00017524, -0.00015399, -0.00012037,
        -7.5545e-05, -2.5328e-05, 2.8266e-05, 7.9945e-05, 0.00012594, 0.00016135, 0.00018176, 0.00018627,
        0.00017264, 0.00014206, 9.6944e-05
    ])
    q = T.(Float64[
        -11.134, -11.046, -10.784, -10.352, -9.7564, -9.0073, -8.116, -7.0968,
        -5.9657, -4.7404, -3.4405, -2.0862, -0.69907, 0.6991, 2.0862, 3.4405,
        4.7405, 5.9657, 7.0968, 8.116, 9.0073, 9.7564, 10.352, 10.784,
        11.046, 11.134, 11.046, 10.784, 10.352, 9.7564, 9.0073, 8.116,
        7.0968, 5.9657, 4.7404, 3.4405, 2.0862, 0.69907, -0.6991, -2.0862,
        -3.4405, -4.7405, -5.9657, -7.0968, -8.116, -9.0073, -9.7564, -10.352,
        -10.784, -11.046, -11.134
    ])

    L1 = T(1) - g[1] * CD24                     # coeff for P(I+1)
    L2 = -T(1) - (g[1] + T(2) * g[2]) * CD24   # coeff for P(I)

    # Variable bounds
    nv   = 2 * N + 2   # 102
    lvar = fill(T(-Inf), nv)
    uvar = fill(T(Inf), nv)
    lvar[1] = T(0); uvar[1] = T(0)   # P(0) fixed at 0
    for i in N+2:2*N+2
        lvar[i] = T(0); uvar[i] = T(1)  # A(0..N) in [0,1]
    end

    c = ExaModels.ExaCore(T; backend = backend, concrete = Val(true))
    ExaModels.@add_var(c, x, nv; lvar = lvar, uvar = uvar, start = T(0))

    # Objective: sum_{J=1}^{N-1} -A(J)*P(J)^2 + (-0.5)*A(N)*P(N)^2
    # P(J)=x[J+1], A(J)=x[N+J+2]
    ExaModels.@add_obj(c, -x[N + d.J + 2] * x[d.J + 1]^2
        for d in [(J = J,) for J in 1:N-1])
    ExaModels.@add_obj(c, T(-1 // 2) * x[2*N + 2] * x[N + 1]^2)

    # N equality constraints (lcon=ucon=0); built up via @add_con!
    c, g_con = ExaModels.add_con(c, N; lcon = T(0), ucon = T(0))

    # Add L1*P(I+1) = L1*x[c_i+1] to constraint c_i for c_i=1..N
    ExaModels.@add_con!(c, g_con, d.ci => L1 * x[d.ci + 1]
        for d in [(ci = ci,) for ci in 1:N])

    # Add L2*P(I) = L2*x[c_i] to constraint c_i for c_i=1..N
    ExaModels.@add_con!(c, g_con, d.ci => L2 * x[d.ci]
        for d in [(ci = ci,) for ci in 1:N])

    # Add CKD2*A(I+1)*P(I+1) = CKD2*x[N+c_i+2]*x[c_i+1] for c_i=1..N
    ExaModels.@add_con!(c, g_con, d.ci => CKD2 * x[N + d.ci + 2] * x[d.ci + 1]
        for d in [(ci = ci,) for ci in 1:N])

    # Add CKD2*A(I)*P(I) = CKD2*x[N+c_i+1]*x[c_i] for c_i=1..N
    ExaModels.@add_con!(c, g_con, d.ci => CKD2 * x[N + d.ci + 1] * x[d.ci]
        for d in [(ci = ci,) for ci in 1:N])

    # Add L3(c_i,j)*P(j-1) = -(g[c_i-j+1]+g[c_i-j+2])*two_CD24 * x[j]
    # for all pairs c_i=2..N, j=2..c_i-1 (P(j-1) = x[j])
    l3_data = [(ci = ci, j = j,
                coeff = -(g[ci - j + 1] + g[ci - j + 2]) * two_CD24)
               for ci in 2:N for j in 2:ci-1]
    if !isempty(l3_data)
        ExaModels.@add_con!(c, g_con, d.ci => d.coeff * x[d.j]
            for d in l3_data)
    end

    # Subtract RHS = (Q(I)+Q(I+1))*D2 from each constraint
    ExaModels.@add_par(c, RHS_par, T[(q[ci] + q[ci + 1]) * D2 for ci in 1:N])
    ExaModels.@add_con!(c, g_con, d.ci => -RHS_par[d.ci]
        for d in [(ci = ci,) for ci in 1:N])

    return ExaModels.ExaModel(c; kwargs...)
end

